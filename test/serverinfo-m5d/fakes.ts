// Bun.serve fakes of local servers for the M5d server-info tests (not a test file itself). Each
// fake answers a fixed route table and records the paths and POST bodies it saw; a route may hang
// until the fake is stopped (the deadline tests).

export interface Fake {
  base: string;
  paths: string[];
  posts: unknown[];
  stop(): void;
}

/** A route: a JSON body (200), a Response maker, or 'hang' (never answers until stop). */
export type Route = unknown | ((body: unknown) => Response) | 'hang';

export function fake(routes: Record<string, Route>): Fake {
  const held: (() => void)[] = [];
  const f: Fake = {
    base: '',
    paths: [],
    posts: [],
    stop: () => {
      for (const r of held) r();
      server.stop(true);
    },
  };
  const server = Bun.serve({
    hostname: '127.0.0.1',
    port: 0,
    async fetch(req) {
      const path = new URL(req.url).pathname;
      f.paths.push(path);
      let body: unknown;
      if (req.method === 'POST') {
        body = await req.json();
        f.posts.push(body);
      }
      const route = routes[path];
      if (route === undefined) return new Response('not found', { status: 404 });
      if (route === 'hang') {
        await new Promise<void>((resolve) => held.push(resolve));
        return new Response('late', { status: 503 });
      }
      if (typeof route === 'function') return (route as (b: unknown) => Response)(body);
      return Response.json(route);
    },
  });
  f.base = `http://127.0.0.1:${server.port}`;
  return f;
}

/** llama.cpp /props as a recent server sends it. */
export function llamaProps(over: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    default_generation_settings: { n_ctx: 8192, params: { temperature: 0.8 } },
    total_slots: 2,
    model_path: 'models/m.gguf',
    build_info: 'b11901-5320c87f',
    endpoint_slots: true,
    endpoint_props: false,
    endpoint_metrics: false,
    ...over,
  };
}

/** Ollama /api/show for a Modelfile with a num_ctx variant. */
export function ollamaShow(blob: string, parameters: string): Record<string, unknown> {
  return {
    modelfile: `# Modelfile generated by "ollama show"\n# To build a new Modelfile based on this, replace FROM with:\n# FROM magmell-16k:latest\n\nFROM ${blob}\nTEMPLATE "{{ .Prompt }}"\n${parameters
      .split('\n')
      .map((l) => `PARAMETER ${l}`)
      .join('\n')}\n`,
    parameters,
    details: { format: 'gguf', family: 'llama' },
    model_info: { 'general.architecture': 'llama', 'llama.context_length': 32768 },
    capabilities: ['completion'],
  };
}
